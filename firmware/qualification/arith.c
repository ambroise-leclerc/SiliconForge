#define CHECK_TABLE(name, type, unsignedType, minimum)                                                              \
    for (uint8_t i = 0; i < sizeof name##cases / sizeof name##cases[0]; ++i) {                                                    \
        struct name##case c;                                                                                             \
        memcpy_P(&c, &name##cases[i], sizeof c);                                                                            \
        const type a = OPAQUE(c.a), b = OPAQUE(c.b);                                                                  \
        const uint8_t shift = OPAQUE(c.shift);                                                                        \
        check((type)(a + b) == c.add);                                                                                \
        check((type)(a - b) == c.sub);                                                                                \
        check((type)((unsignedType)a * (unsignedType)b) == c.mul);                                                    \
        if (b != 0 && !(a == (minimum) && b == (type)-1)) {                                                           \
            check((type)(a / b) == c.div);                                                                            \
            check((type)(a % b) == c.mod);                                                                            \
        }                                                                                                             \
        check((type)((unsignedType)a << shift) == c.shl);                                                             \
        check((type)(a >> shift) == c.shr);                                                                           \
        check((a < b) == (c.sub != 0 && ((minimum) != 0 ? (int64_t)c.a < (int64_t)c.b : (uint64_t)c.a < (uint64_t)c.b))); \
    }

